import { mkdtemp, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { expect, test } from "../support/fixtures.js";
import { startAppServer } from "../support/appServer.js";
import { openNativeTab } from "../support/nativeTab.js";
for (const mode of ["roundtrip", "pause-resume", "cancel", "no-overwrite", "multi-pause"] as const)
  test(`desktop file transfer generated ${mode}`, async ({ page, appServer }) => {
    test.setTimeout(60000);
    const root = await mkdtemp(join(tmpdir(), "soda-desktop-files-e2e-"));
    const env = {
      SODA_DESKTOP_COMMAND: JSON.stringify([
        process.execPath,
        fileURLToPath(
          new URL("../../../../scripts/remote-desktop/synthetic-helper.mjs", import.meta.url),
        ),
        "--static",
      ]),
    };
    const saved = process.env.SODA_DESKTOP_COMMAND;
    Object.assign(process.env, env);
    const provider = await startAppServer().finally(() => {
      if (saved === undefined) delete process.env.SODA_DESKTOP_COMMAND;
      else process.env.SODA_DESKTOP_COMMAND = saved;
    });
    const frames: { url: string; type?: string; action?: string }[] = [];
    page.on("websocket", (socket) =>
      socket.on("framesent", ({ payload }) => {
        if (typeof payload !== "string") return;
        try {
          const m = JSON.parse(payload);
          if (m.type === "desktop_file")
            frames.push({ url: socket.url(), type: m.type, action: m.request.action });
        } catch {}
      }),
    );
    if (mode === "pause-resume" || mode === "cancel" || mode === "multi-pause")
      await page.addInitScript(() => {
        const Base = WebSocket;
        window.WebSocket = class extends Base {
          send(data: string | ArrayBufferLike | Blob | ArrayBufferView) {
            if (typeof data === "string") {
              const m = JSON.parse(data);
              if (m.type === "desktop_file" && ["read", "write"].includes(m.request.action)) {
                setTimeout(() => {
                  if (this.readyState === WebSocket.OPEN) super.send(data);
                }, 100);
                return;
              }
            }
            super.send(data);
          }
        };
      });
    try {
      const owner = await provider.openClient();
      await owner.request("desktop.settings.set", {
        enabled: true,
        allowInput: false,
        allowClipboard: false,
        allowDisplayResize: false,
        fileRoot: root,
      });
      if (mode === "no-overwrite")
        await writeFile(join(root, "generated.bin"), "original generated");
      const a = await appServer.openClient(),
        invite = await a.request("machine.invite", { label: "File fixture B" });
      await owner.request("machine.delegate", {
        url: appServer.origin,
        machineId: invite.machineId,
        token: invite.token,
      });
      if (mode === "multi-pause") await page.clock.install();
      await page.goto(`${appServer.origin}/#token=${appServer.token}`);
      const header = page.locator(`[data-machine-id="${invite.machineId}"]`);
      await expect(header.locator('[data-state="online"]')).toBeVisible();
      await openNativeTab(page, "desktop", header);
      const view = page.locator("[data-remote-desktop]"),
        panel = view.locator("[data-desktop-files]");
      await expect(view.getByLabel("共有画面")).toHaveAttribute("data-rendered-frames", /^[1-9]/);
      await panel.locator("summary").click();
      await panel.getByRole("button", { name: "ファイル転送を許可", exact: true }).click();
      await expect(panel.getByText("共有フォルダ:", { exact: false })).toContainText(root);
      const size = mode === "roundtrip" || mode === "no-overwrite" ? 120000 : 1048576;
      // Real browser D&D, generated bytes only, targeting a private temporary folder.
      const data = await page.evaluateHandle(
        ({ size, count }) => {
          const transfer = new DataTransfer();
          for (let i = 0; i < count; i++)
            transfer.items.add(
              new File(
                [new Uint8Array(size).fill(0xab)],
                count === 1 ? "generated.bin" : `generated-${i}.bin`,
                { type: "application/octet-stream" },
              ),
            );
          return transfer;
        },
        { size, count: mode === "multi-pause" ? 5 : 1 },
      );
      await view.dispatchEvent("drop", { dataTransfer: data });
      await data.dispose();
      const jobs = panel.getByRole("list", { name: "ファイル転送の一覧" });
      if (mode === "multi-pause") {
        for (let i = 0; i < 5; i++) {
          const job = jobs.locator("li").nth(i);
          await expect(job).toContainText(/— [1-9][0-9]* \/ /);
          await job.getByRole("button", { name: "一時停止", exact: true }).click();
          await expect(job.getByRole("button", { name: "再開", exact: true })).toBeVisible();
        }
        await page.clock.fastForward(21000);
        await expect
          .poll(() => frames.filter((f) => f.action === "status").length)
          .toBeGreaterThanOrEqual(5);
        await expect(jobs.getByRole("button", { name: "再開", exact: true })).toHaveCount(5);
        expect(await jobs.textContent()).not.toContain("失敗");
        await panel.getByRole("button", { name: "ファイル転送を解除", exact: true }).click();
        await expect(
          panel.getByRole("button", { name: "ファイル転送を許可", exact: true }),
        ).toBeEnabled();
        await expect(jobs).toContainText("取消済み");
        await expect.poll(() => readdir(root)).toEqual([]);
        return;
      }
      if (mode === "no-overwrite") {
        await expect(jobs).toContainText("失敗");
        expect(await readFile(join(root, "generated.bin"), "utf8")).toBe("original generated");
        return;
      }
      if (mode === "pause-resume") {
        await jobs.getByRole("button", { name: "一時停止", exact: true }).click();
        await expect(jobs.getByRole("button", { name: "再開", exact: true })).toBeVisible();
        await expect
          .poll(async () => {
            try {
              await readFile(join(root, "generated.bin"));
              return true;
            } catch {
              return false;
            }
          })
          .toBe(false);
        await jobs.getByRole("button", { name: "再開", exact: true }).click();
      } else if (mode === "cancel") {
        await expect
          .poll(() => frames.filter((f) => f.action === "write").length)
          .toBeGreaterThan(0);
        await jobs.getByRole("button", { name: "取り消す", exact: true }).click();
        await expect(jobs).toContainText("取消済み");
        await expect.poll(() => readdir(root)).toEqual([]);
        return;
      }
      await expect(jobs).toContainText("完了");
      expect(await readFile(join(root, "generated.bin"))).toEqual(Buffer.alloc(size, 0xab));
      const download = page.waitForEvent("download");
      await panel.getByRole("button", { name: "ダウンロード", exact: true }).click();
      const received = await download;
      expect(received.suggestedFilename()).toBe("generated.bin");
      expect(await readFile((await received.path())!)).toEqual(Buffer.alloc(size, 0xab));
      await expect(jobs).toContainText("ブラウザのダウンロードへ渡しました");
      expect(frames.filter((f) => f.action === "write").length).toBeGreaterThan(1);
      await panel.getByLabel("共有フォルダ内の場所").fill("../");
      await panel.getByRole("button", { name: "一覧を更新", exact: true }).click();
      await expect(panel.getByRole("status")).toContainText("相対パス");
    } finally {
      await provider.close();
      await rm(root, { recursive: true, force: true });
    }
  });

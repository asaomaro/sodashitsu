$ErrorActionPreference='Stop'
$script=Join-Path $PSScriptRoot 'protect-endpoint-key.ps1'
function Invoke-Generated([string]$operation,[byte[]]$bytes,[int]$expected) {
    $info=New-Object Diagnostics.ProcessStartInfo
    $info.FileName=Join-Path ([Environment]::GetFolderPath('System')) 'WindowsPowerShell\v1.0\powershell.exe';$info.Arguments='-NoLogo -NoProfile -NonInteractive -ExecutionPolicy Bypass -File "'+$script+'" -Operation '+$operation
    $info.WorkingDirectory=[Environment]::GetFolderPath('System');$info.EnvironmentVariables['PSModulePath']=Join-Path $PSHOME 'Modules';$info.UseShellExecute=$false;$info.CreateNoWindow=$true;$info.RedirectStandardInput=$true;$info.RedirectStandardOutput=$true;$info.RedirectStandardError=$true
    # Process.StandardInput constructs an AutoFlush text writer. On UTF8 hosts
    # its preamble can be written even before BaseStream is used. Binary tests
    # must select the no-preamble encoding before that writer is constructed.
    $previousEncoding=[Console]::InputEncoding
    [Console]::InputEncoding=New-Object Text.UTF8Encoding($false)
    $child=New-Object Diagnostics.Process;$child.StartInfo=$info;$memory=New-Object IO.MemoryStream;$started=$false
    try {
        [void]$child.Start();$started=$true;$copy=$child.StandardOutput.BaseStream.CopyToAsync($memory);$errors=$child.StandardError.ReadToEndAsync()
        $child.StandardInput.BaseStream.Write($bytes,0,$bytes.Length);$child.StandardInput.BaseStream.Close()
        if(-not $child.WaitForExit(10000) -or -not $copy.Wait(1000) -or -not $errors.Wait(1000)){throw 'Generated endpoint helper timed out'}
        if($child.ExitCode -ne $expected){throw ('Generated endpoint helper exit mismatch: operation='+$operation+', expected='+$expected+', actual='+$child.ExitCode+', diagnostic='+$errors.Result)}
        return ,$memory.ToArray()
    } finally {
        try {if($started -and -not $child.HasExited){$child.Kill()}}
        finally {try {$child.Dispose();$memory.Dispose()} finally {[Console]::InputEncoding=$previousEncoding}}
    }
}
# Own generated bytes only. Never loads a real endpoint identity or desktop.
$plain=[Text.Encoding]::UTF8.GetBytes('Sodashitsu generated endpoint check only')
$encrypted=Invoke-Generated 'protect' $plain 0
if($encrypted.Length -le $plain.Length){throw 'Missing generated protection'}
$decrypted=Invoke-Generated 'unprotect' $encrypted 0
if([Convert]::ToBase64String($decrypted) -ne [Convert]::ToBase64String($plain)){throw 'Generated round trip mismatch'}
$invalid=Invoke-Generated 'unprotect' ([byte[]](1,2,3)) 1
if($invalid.Length -ne 0){throw 'Invalid ciphertext leaked output'}
$large=Invoke-Generated 'protect' (New-Object byte[] 65537) 1
if($large.Length -ne 0){throw 'Oversize input leaked output'}
'endpoint_key_generated_checks_passed'

# In-memory ACL policy checks; no actual filesystem permissions are changed.
. (Join-Path $PSScriptRoot 'EndpointAclPolicy.ps1')
$user=[Security.Principal.WindowsIdentity]::GetCurrent().User.Value
function Rule([string]$sid,[Security.AccessControl.FileSystemRights]$rights,[Security.AccessControl.PropagationFlags]$flags) {
    return [pscustomobject]@{AccessControlType=[Security.AccessControl.AccessControlType]::Allow;IdentityReference=[Security.Principal.SecurityIdentifier]::new($sid);FileSystemRights=$rights;PropagationFlags=$flags}
}
$allow=Rule $user ([Security.AccessControl.FileSystemRights]::FullControl) ([Security.AccessControl.PropagationFlags]::None)
if(-not (Test-SodaEndpointAcl $user @($allow) $user $true)){throw 'Generated private ACL denied'}
$world=Rule 'S-1-1-0' ([Security.AccessControl.FileSystemRights]::Write) ([Security.AccessControl.PropagationFlags]::None)
if(Test-SodaEndpointAcl $user @($allow,$world) $user $true){throw 'Generated world writer allowed'}
$delete=Rule 'S-1-1-0' ([Security.AccessControl.FileSystemRights]::DeleteSubdirectoriesAndFiles) ([Security.AccessControl.PropagationFlags]::None)
if(Test-SodaEndpointAcl $user @($allow,$delete) $user $false){throw 'Generated ancestor replacement allowed'}
$read=Rule 'S-1-1-0' ([Security.AccessControl.FileSystemRights]::Read) ([Security.AccessControl.PropagationFlags]::None)
if(-not (Test-SodaEndpointAcl $user @($allow,$read) $user $true)){throw 'Generated read-only ACL denied'}
$installer='S-1-5-80-956008885-3418522649-1831038044-1853292631-2271478464'
if(-not (Test-SodaEndpointAcl $installer @() $user $false) -or (Test-SodaEndpointAcl $installer @() $user $true)){throw 'Installer owner boundary changed'}
if(-not (Test-SodaEndpointDrive ([IO.DriveType]::Fixed))){throw 'Generated fixed drive denied'}
foreach($kind in @([IO.DriveType]::Network,[IO.DriveType]::Unknown,[IO.DriveType]::NoRootDirectory,[IO.DriveType]::Removable)){if(Test-SodaEndpointDrive $kind){throw 'Generated nonlocal drive accepted'}}
'endpoint_acl_generated_checks_passed'

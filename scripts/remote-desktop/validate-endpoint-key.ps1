    if($LASTEXITCODE -ne 0 -or (Test-Path -LiteralPath $source) -or [Convert]::ToBase64String([IO.File]::ReadAllBytes($destination)) -ne 'BwgJ'){throw 'Generated write-through replace failed'}
} finally {[IO.Directory]::Delete($stage,$true)}
'endpoint_commit_generated_checks_passed'
exit 0

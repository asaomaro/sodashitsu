const {app,BrowserWindow,clipboard,session}=require('electron');
const http=require('node:http');
const {pathToFileURL}=require('node:url');
app.setPath('userData','/tmp/soda-electron-clipboard-fixture/user-data');
app.disableHardwareAcceleration();
let server;
const timer=setTimeout(()=>{console.error('fixture timeout');app.exit(2)},30000);
app.whenReady().then(async()=>{
 const {PanelClipboard}=await import(pathToFileURL('/workspaces/sodashitsu-electron-clipboard/packages/desktop-assistant/dist/panelClipboard.js'));
 const policy=new PanelClipboard();const events=[];let fixed=false;
 server=http.createServer((req,res)=>{res.setHeader('Content-Type','text/html');res.end('<textarea id="text">generated terminal selection</textarea><iframe src="/child"></iframe>');});
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
 const origin=`http://127.0.0.1:${server.address().port}`;
 const ses=session.fromPartition('fixture');
 ses.setPermissionCheckHandler((wc,p,o,d)=>{events.push({phase:'check',p,main:d.isMainFrame});return fixed&&policy.permits(wc,p,d)});
 ses.setPermissionRequestHandler((wc,p,cb,d)=>{events.push({phase:'request',p,main:d.isMainFrame});cb(fixed&&policy.permits(wc,p,d))});
 const win=new BrowserWindow({width:500,height:300,webPreferences:{partition:'fixture',sandbox:true,contextIsolation:true,nodeIntegration:false}});
 policy.register(win.webContents,origin);await win.loadURL(origin);win.focus();win.webContents.focus();
 const copy=`(async()=>{const t=document.querySelector('textarea');t.focus();t.select();try {await navigator.clipboard.writeText(t.value);return true}catch{return false}})()`;
 const denied=await win.webContents.executeJavaScript(copy,true);
 fixed=true;
 const copied=await win.webContents.executeJavaScript(copy,true);
 const match=(await clipboard.readText())==='generated terminal selection';
 const readDenied=await win.webContents.executeJavaScript(`navigator.clipboard.readText().then(()=>false,()=>true)`,true);
 const subframe=win.webContents.mainFrame.frames[0];
 const iframeDenied=await subframe.executeJavaScript(`navigator.clipboard.writeText('generated child').then(()=>false,()=>true)`,true);
 policy.forget(win.webContents);
 const revoked=await win.webContents.executeJavaScript(copy,true);
 const result={electron:process.versions.electron,oldDenied:denied===false,selectedTextCopied:copied,generatedClipboardMatches:match,readDenied,iframeDenied,closedScopeDenied:revoked===false,permissionEvents:events};
 console.log(JSON.stringify(result));
 win.destroy();server.close();clearTimeout(timer);
 app.exit(Object.values(result).slice(1,7).every(Boolean)?0:1);
}).catch(error=>{console.error(error.name+': '+error.message);app.exit(1)});
